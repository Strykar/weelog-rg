"""Inline the weelog_rg package into weechat/weelog.py as one self-contained file.

weechat.org takes one file per script, so the split sources are joined here:
the four core modules in dependency order, then the script body with its
package imports removed. Writes dist/weelog.py unless a path is given.

    python3 scripts/build-weechat-script.py [OUT]
"""
from __future__ import annotations

import ast
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
MODULES = ("parse", "index", "query", "search")
SCRIPT = REPO / "weechat" / "weelog.py"
GENERATED_NOTE = (
    "# Generated by scripts/build-weechat-script.py from weechat/weelog.py and the\n"
    "# weelog_rg package in the upstream repository. Edit those, not this file.\n"
)


def _is_package_import(node: ast.stmt) -> bool:
    return isinstance(node, ast.ImportFrom) and (
        node.level > 0 or (node.module or "").split(".")[0] == "weelog_rg"
    )


def _is_import_core(node: ast.stmt) -> bool:
    if isinstance(node, ast.FunctionDef):
        return node.name == "_import_core"
    return (isinstance(node, ast.Expr) and isinstance(node.value, ast.Call)
            and isinstance(node.value.func, ast.Name) and node.value.func.id == "_import_core")


def split(src: str, imports: dict[str, set[str]], plain: set[str]) -> str:
    """Strip imports, docstring and package glue; return the remaining top-level code."""
    tree = ast.parse(src)
    lines = src.splitlines()
    kept: list[tuple[int, int]] = []
    for i, node in enumerate(tree.body):
        if isinstance(node, ast.ImportFrom):
            if node.module == "__future__" or _is_package_import(node):
                continue
            if node.module == "weechat":
                raise SystemExit("unexpected 'from weechat import'")
            imports.setdefault(node.module or "", set()).update(a.name for a in node.names)
            continue
        if isinstance(node, ast.Import):
            plain.update(a.name for a in node.names)
            continue
        if i == 0 and isinstance(node, ast.Expr) and isinstance(node.value, ast.Constant) \
                and isinstance(node.value.value, str):
            continue
        if _is_import_core(node):
            continue
        start = node.lineno
        for d in getattr(node, "decorator_list", []):
            start = min(start, d.lineno)
        j = start - 1
        while j - 1 >= 0 and lines[j - 1].startswith("#"):
            j -= 1
        kept.append((j, node.end_lineno))
    return "\n\n\n".join("\n".join(lines[a:b]) for a, b in kept)


def header(src: str) -> str:
    out = []
    for line in src.splitlines():
        if not line.startswith("#"):
            break
        if line.startswith("# This file imports the weelog_rg package"):
            break
        out.append(line)
    while out and out[-1] == "#":
        out.pop()
    return "\n".join(out) + "\n#\n" + GENERATED_NOTE


def build() -> str:
    imports: dict[str, set[str]] = {}
    plain: set[str] = set()
    parts = []
    for name in MODULES:
        path = REPO / "weelog_rg" / f"{name}.py"
        body = split(path.read_text(encoding="utf-8"), imports, plain)
        parts.append(f"# ---- weelog_rg/{name}.py ----\n\n{body}")
    script_src = SCRIPT.read_text(encoding="utf-8")
    parts.append("# ---- weechat/weelog.py ----\n\n" + split(script_src, imports, plain))

    plain.discard("weechat")
    import_lines = [f"import {m}" for m in sorted(plain)]
    for mod in sorted(imports):
        names = ", ".join(sorted(imports[mod]))
        line = f"from {mod} import {names}"
        if len(line) > 88:
            line = f"from {mod} import (\n    " + ",\n    ".join(sorted(imports[mod])) + ",\n)"
        import_lines.append(line)
    import_lines.append("")
    import_lines.append("import weechat")

    out = header(script_src) + "\nfrom __future__ import annotations\n\n"
    out += "\n".join(import_lines) + "\n\n\n" + "\n\n\n".join(parts) + "\n"
    compile(out, "weelog.py", "exec")
    for bad in ("import weelog_rg", "from weelog_rg", "from .", "_import_core"):
        if bad in out:
            raise SystemExit(f"build left package glue behind: {bad!r}")
    return out


def main(argv: list[str]) -> int:
    out_path = Path(argv[1]) if len(argv) > 1 else REPO / "dist" / "weelog.py"
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(build(), encoding="utf-8")
    print(f"wrote {out_path} ({out_path.stat().st_size} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
