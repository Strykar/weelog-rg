from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
BUILD = REPO_ROOT / "scripts" / "build-weechat-script.py"


def test_built_script_is_self_contained(tmp_path):
    out = tmp_path / "weelog.py"
    subprocess.run([sys.executable, str(BUILD), str(out)], check=True, capture_output=True)
    src = out.read_text(encoding="utf-8")
    lines = src.splitlines()
    assert not src.startswith("#!")
    assert lines[0].startswith("# SPDX-FileCopyrightText: 2026 Strykar <")
    assert any(ln.startswith("# SPDX-License-Identifier: MIT") for ln in lines[:5])
    assert "Generated by scripts/build-weechat-script.py" in src
    assert re.search(r"^(from|import) weelog_rg", src, re.M) is None
    assert "_import_core" not in src
    assert src.count("from __future__ import annotations") == 1
    first_code = next(ln for ln in lines if ln and not ln.startswith("#"))
    assert first_code == "from __future__ import annotations"
    assert 'weechat.register("weelog"' in src or "weechat.register(SCRIPT_NAME" in src

    # -I keeps cwd and the repo off sys.path, so a leftover package import would fail.
    stub = tmp_path / "stub"
    stub.mkdir()
    (stub / "weechat.py").write_text(
        "WEECHAT_RC_OK = 0\nWEECHAT_RC_ERROR = -1\n"
        "WEECHAT_HOOK_PROCESS_RUNNING = -1\nWEECHAT_HOOK_PROCESS_ERROR = -2\n")
    probe = f"""
import sys, runpy
sys.path.insert(0, {str(stub)!r})
g = runpy.run_path({str(out)!r}, run_name="weelog_built")
assert "weelog_rg" not in sys.modules
req = g["parse_command"]("-nick alice -from 2026-01-01 hello world")
assert (req.nick, req.text, str(req.date_from)) == ("alice", "hello world", "2026-01-01"), req
assert g["classify_buffer"]("libera", "#arch") == "channel"           # index.py
assert g["parse_line"]("t\\tn\\tm\\n") == ("t", "n", "m", False)        # parse.py
assert g["rg_args"](g["Query"](text="x"))[:2] == ["rg", "--json"]     # query.py + search.py
assert g["LineBuffer"]().feed("a\\nb") == [b"a"]                      # script
print("ok")
"""
    r = subprocess.run([sys.executable, "-I", "-c", probe], capture_output=True, text=True,
                       cwd=str(tmp_path))
    assert r.returncode == 0 and r.stdout.strip() == "ok", r.stderr


def test_build_is_deterministic(tmp_path):
    a, b = tmp_path / "a.py", tmp_path / "b.py"
    subprocess.run([sys.executable, str(BUILD), str(a)], check=True, capture_output=True)
    subprocess.run([sys.executable, str(BUILD), str(b)], check=True, capture_output=True)
    assert a.read_bytes() == b.read_bytes()
